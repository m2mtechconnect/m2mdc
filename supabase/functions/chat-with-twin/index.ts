import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
};

serve(async (req) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { messages, templateContext } = await req.json();
    
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    if (!LOVABLE_API_KEY) {
      throw new Error("LOVABLE_API_KEY is not configured");
    }

    // Build system prompt with template context
    const systemPrompt = templateContext?.system_prompt || "You are a helpful Digital Twin assistant.";
    const contextualPrompt = `${systemPrompt}

TEMPLATE CONTEXT:
- Name: ${templateContext?.name || "Unknown"}
- Industry: ${templateContext?.industry || "General"}
- Department: ${templateContext?.department || "Operations"}
- Twin Type: ${templateContext?.twin_type || "operational"}

CAPABILITIES:
${templateContext?.copilot_prompts?.capabilities?.map((c: string) => `- ${c}`).join('\n') || '- General automation'}

LIMITATIONS:
${templateContext?.copilot_prompts?.limitations?.map((l: string) => `- ${l}`).join('\n') || '- None specified'}

WORKFLOW OVERVIEW:
${templateContext?.blueprint?.workflow_steps?.map((s: any) => `${s.label}`).join(' → ') || 'Not specified'}

Answer questions about this Digital Twin clearly and concisely. Explain what it does, how it works, what scenarios it handles, and any limitations. Be specific and avoid vague statements.`;

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        "Authorization": `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-2.5-flash",
        messages: [
          { role: "system", content: contextualPrompt },
          ...messages,
        ],
        stream: true,
      }),
    });

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(
          JSON.stringify({ error: "Rate limit exceeded. Please try again later." }),
          {
            status: 429,
            headers: { ...corsHeaders, "Content-Type": "application/json" },
          }
        );
      }
      if (response.status === 402) {
        return new Response(
          JSON.stringify({ error: "Payment required. Please add credits to your Lovable workspace." }),
          {
            status: 402,
            headers: { ...corsHeaders, "Content-Type": "application/json" },
          }
        );
      }
      const errorText = await response.text();
      console.error("AI gateway error:", response.status, errorText);
      return new Response(
        JSON.stringify({ error: "AI gateway error" }),
        {
          status: 500,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        }
      );
    }

    return new Response(response.body, {
      headers: { ...corsHeaders, "Content-Type": "text/event-stream" },
    });
  } catch (error) {
    console.error("chat-with-twin error:", error);
    return new Response(
      JSON.stringify({ error: error instanceof Error ? error.message : "Unknown error" }),
      {
        status: 500,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      }
    );
  }
});